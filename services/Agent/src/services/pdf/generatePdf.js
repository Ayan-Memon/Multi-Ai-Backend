import PDFDocument from "pdfkit";

const primary = "#1449e6";
const dark = "#171717";
const muted = "#666666";
const border = "#e5e7eb";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      bufferPages: true,
      margins: {
        top: 55,
        bottom: 75,
        left: 55,
        right: 55,
      },
      info: {
        Title: data.title,
        Author: "Nexora",
        Creator: "Nexora",
      },
    });

    const chunks = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    doc.fontSize(11).fillColor(primary).font("Helvetica-Bold").text("NEXORA");

    doc
      .moveDown(0.6)
      .moveTo(55, doc.y)
      .lineTo(540, doc.y)
      .lineWidth(1)
      .strokeColor(border)
      .stroke();

    doc.moveDown(2);

    doc
      .font("Helvetica-Bold")
      .fontSize(28)
      .fillColor(dark)
      .text(data.title, { lineGap: 4 });

    if (data.subtitle) {
      doc
        .moveDown(0.7)
        .font("Helvetica")
        .fontSize(12)
        .fillColor(muted)
        .text(data.subtitle, { lineGap: 4 });
    }

    doc.moveDown(2);

    data?.sections?.forEach((section, index) => {
      doc
        .font("Helvetica-Bold")
        .fontSize(17)
        .fillColor(dark)
        .text(section.heading, { lineGap: 3 });

      doc.moveDown(0.7);

      const lineY = doc.y;
      doc
        .moveTo(55, lineY)
        .lineTo(80, lineY)
        .lineWidth(3)
        .strokeColor(primary)
        .stroke();

      doc.moveDown(0.9);

      section?.points?.forEach((point) => {
        const startY = doc.y;

        doc
          .circle(62, startY + 6, 2.5)
          .fillColor(primary)
          .fill();

        doc
          .font("Helvetica")
          .fontSize(11.5)
          .fillColor(dark)
          .text(point, 75, startY, {
            width: 465,
            lineGap: 4,
            paragraphGap: 7,
          });

        doc.moveDown(0.2);
      });

      if (index !== data.sections.length - 1) {
        doc.moveDown(1.2);
      }
    });

    const range = doc.bufferedPageRange();
    const lastPageIndex = range.start + range.count - 1;
    const footerY = 755;

    doc.switchToPage(lastPageIndex);
    doc.page.margins.bottom = 0;

    doc
      .moveTo(55, footerY)
      .lineTo(540, footerY)
      .lineWidth(0.7)
      .strokeColor(border)
      .stroke();

    doc
      .font("Helvetica")
      .fontSize(9)
      .fillColor(muted)
      .text("Generated by Nexora", 55, footerY + 12);

    doc
      .fontSize(9)
      .fillColor(muted)
      .text("NEXORA", 55, footerY + 12, {
        width: 485,
        align: "right",
      });

    doc.end();
  });
};
